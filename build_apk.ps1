param(
    [switch]$Deploy = $false,
    [switch]$NoBump = $false
)

$ErrorActionPreference = "Stop"

Write-Host "=== 1. Flutter & Android SDK muhiti sozlanmoqda ===" -ForegroundColor Cyan
$env:JAVA_HOME = "C:\Program Files\Microsoft\jdk-17.0.21.102-hotspot"
$env:ANDROID_HOME = "C:\dev\android-sdk"
$env:ANDROID_SDK_ROOT = "C:\dev\android-sdk"
$env:Path = "C:\dev\flutter\bin;$env:JAVA_HOME\bin;C:\dev\android-sdk\platform-tools;$env:Path"

$RootDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$PubspecPath = "$RootDir\mobile\pubspec.yaml"
$VersionDartPath = "$RootDir\mobile\lib\version.dart"
$DistDir = "$RootDir\dist"
New-Item -ItemType Directory -Force -Path $DistDir | Out-Null

# Read and auto-increment version in pubspec.yaml (e.g. 1.0.4+4 -> 1.0.5+5)
$PubspecContent = Get-Content $PubspecPath -Raw
if ($PubspecContent -match '(?m)^version:\s*(\d+)\.(\d+)\.(\d+)\+(\d+)') {
    $Major = [int]$Matches[1]
    $Minor = [int]$Matches[2]
    $Patch = [int]$Matches[3]
    $Build = [int]$Matches[4]

    if (-not $NoBump) {
        $Patch += 1
        $Build += 1
    }

    $NewVersion = "$Major.$Minor.$Patch"
    $NewFull = "$NewVersion+$Build"

    $PubspecContent = $PubspecContent -replace '(?m)^version:\s*\d+\.\d+\.\d+\+\d+', "version: $NewFull"
    Set-Content -Path $PubspecPath -Value $PubspecContent -Encoding UTF8 -NoNewline

    $DartContent = @"
// GENERATED BY build_apk.ps1 — DO NOT EDIT MANUALLY
const String kAppVersion = '$NewVersion';
const int kAppBuildNumber = $Build;
const String kAppFullVersion = '$NewFull';
"@
    Set-Content -Path $VersionDartPath -Value $DartContent -Encoding UTF8

    $BuiltAt = (Get-Date).ToString("yyyy-MM-dd HH:mm")
    $JsonContent = @{
        version  = $NewVersion
        build    = $Build
        full     = $NewFull
        built_at = $BuiltAt
    } | ConvertTo-Json
    Set-Content -Path "$DistDir\apk_version.json" -Value $JsonContent -Encoding UTF8

    Write-Host "📦 Avto-versiya yangilandi: v$NewVersion (build #$Build)" -ForegroundColor Yellow
}
else {
    throw "pubspec.yaml ichida 'version: X.Y.Z+B' qatori topilmadi!"
}

Push-Location "$RootDir\mobile"

try {
    Write-Host "=== 2. Kod tahlili (flutter analyze) ===" -ForegroundColor Cyan
    flutter analyze

    Write-Host "=== 3. Release APK yig'ilmoqda (v$NewVersion+$Build) ===" -ForegroundColor Cyan
    flutter build apk --release --target-platform android-arm,android-arm64 --build-name=$NewVersion --build-number=$Build

    $BuiltApk = "$RootDir\mobile\build\app\outputs\flutter-apk\app-release.apk"
    $DistApk = "$DistDir\hisobchi.apk"
    $VersionedApk = "$DistDir\Hisobchi_v$NewVersion.apk"

    Copy-Item -Force $BuiltApk $DistApk
    Copy-Item -Force $BuiltApk $VersionedApk

    $SizeMb = [math]::Round((Get-Item $DistApk).Length / 1MB, 2)
    Write-Host "✅ APK muvaffaqiyatli yig'ildi: $DistApk (v$NewVersion, $SizeMb MB)" -ForegroundColor Green

    if ($Deploy) {
        $TargetFile = "$RootDir\.deploy_target"
        $DeployTarget = if ($env:HISOBCHI_DEPLOY_TARGET) {
            $env:HISOBCHI_DEPLOY_TARGET.Trim()
        } elseif (Test-Path $TargetFile) {
            (Get-Content $TargetFile -Raw).Trim()
        } else {
            throw ".deploy_target fayli yoki HISOBCHI_DEPLOY_TARGET o'zgaruvchisi topilmadi!"
        }
        Write-Host "=== 4. Serverga APK va versiya ma'lumoti yuklanmoqda ===" -ForegroundColor Cyan
        scp "$DistDir\apk_version.json" $DistApk $DeployTarget
        Write-Host "🚀 Serverdagi APK v$NewVersion (#$Build) ga yangilandi!" -ForegroundColor Green
    }
}
finally {
    Pop-Location
}
