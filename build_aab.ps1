param(
    [switch]$NoBump = $false
)

$ErrorActionPreference = "Stop"

Write-Host "=== 1. Flutter & Android SDK muhiti sozlanmoqda ===" -ForegroundColor Cyan
$env:JAVA_HOME = "C:\Program Files\Microsoft\jdk-17.0.21.102-hotspot"
$env:ANDROID_HOME = "C:\dev\android-sdk"
$env:ANDROID_SDK_ROOT = "C:\dev\android-sdk"
$env:Path = "C:\dev\flutter\bin;$env:JAVA_HOME\bin;C:\dev\android-sdk\platform-tools;$env:Path"

$RootDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$KeyPropsPath = "$RootDir\mobile\android\key.properties"
$KeystorePath = "$RootDir\mobile\android\upload-keystore.jks"
if (-not (Test-Path $KeyPropsPath) -or -not (Test-Path $KeystorePath)) {
    throw "Play Market uchun release imzolash kalitlari topilmadi ($KeyPropsPath va $KeystorePath)!"
}

$PubspecPath = "$RootDir\mobile\pubspec.yaml"
$VersionDartPath = "$RootDir\mobile\lib\version.dart"
$DistDir = "$RootDir\dist"
New-Item -ItemType Directory -Force -Path $DistDir | Out-Null

$PubspecContent = Get-Content $PubspecPath -Raw
if ($PubspecContent -match '(?m)^version:\s*(\d+)\.(\d+)\.(\d+)\+(\d+)') {
    $Major = [int]$Matches[1]
    $Minor = [int]$Matches[2]
    $Patch = [int]$Matches[3]
    $Build = [int]$Matches[4]

    if (-not $NoBump) {
        $Patch += 1
        $Build += 1
    }

    $NewVersion = "$Major.$Minor.$Patch"
    $NewFull = "$NewVersion+$Build"

    $PubspecContent = $PubspecContent -replace '(?m)^version:\s*\d+\.\d+\.\d+\+\d+', "version: $NewFull"
    Set-Content -Path $PubspecPath -Value $PubspecContent -Encoding UTF8 -NoNewline

    $DartContent = @"
// GENERATED BY build_aab.ps1 — DO NOT EDIT MANUALLY
const String kAppVersion = '$NewVersion';
const int kAppBuildNumber = $Build;
const String kAppFullVersion = '$NewFull';
"@
    Set-Content -Path $VersionDartPath -Value $DartContent -Encoding UTF8

    Write-Host "📦 Play Market versiyasi: v$NewVersion (build #$Build)" -ForegroundColor Yellow
}
else {
    throw "pubspec.yaml ichida 'version: X.Y.Z+B' qatori topilmadi!"
}

$SymbolsDir = "$DistDir\debug-symbols\v$NewVersion"
New-Item -ItemType Directory -Force -Path $SymbolsDir | Out-Null

Push-Location "$RootDir\mobile"

try {
    Write-Host "=== 2. Kod tahlili (flutter analyze) ===" -ForegroundColor Cyan
    flutter analyze
    if ($LASTEXITCODE -ne 0) { throw "flutter analyze xatolik bilan tugadi!" }

    Write-Host "=== 3. Play Market App Bundle (.aab) yig'ilmoqda (v$NewVersion+$Build) ===" -ForegroundColor Cyan
    flutter build appbundle --release --flavor play --dart-define=PLAY_STORE=true --obfuscate --split-debug-info="$SymbolsDir" --build-name=$NewVersion --build-number=$Build
    if ($LASTEXITCODE -ne 0) { throw "flutter build appbundle xatolik bilan tugadi!" }

    $BuiltAab = "$RootDir\mobile\build\app\outputs\bundle\playRelease\app-play-release.aab"
    if (-not (Test-Path $BuiltAab)) {
        throw "AAB fayl topilmadi: $BuiltAab"
    }

    $DistAab = "$DistDir\hisobchi-play.aab"
    $VersionedAab = "$DistDir\Hisobchi_Play_v$NewVersion.aab"

    Copy-Item -Force $BuiltAab $DistAab
    Copy-Item -Force $BuiltAab $VersionedAab

    $SizeMb = [math]::Round((Get-Item $DistAab).Length / 1MB, 2)
    Write-Host "✅ Play Market AAB muvaffaqiyatli yig'ildi: $DistAab (v$NewVersion, $SizeMb MB)" -ForegroundColor Green
    Write-Host "🔐 Debug/obfuscation simvollari: $SymbolsDir" -ForegroundColor DarkGray
}
finally {
    Pop-Location
}
